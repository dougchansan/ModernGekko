    c = contour(m, 0.5).astype(np.float32)
    (x, y), r = cv2.minEnclosingCircle(c)
    area_r = math.sqrt(cv2.contourArea(c) / math.pi)
    r = (r + area_r) / 2
    return ((x - cx) / scale, (y - cy) / scale, r / scale)



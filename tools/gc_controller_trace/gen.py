def emit_poly(name, pts):
    # ImGui fills clockwise polygons (screen coordinates, y down) only.
    n = len(pts)
    area = sum(pts[i][0] * pts[(i + 1) % n][1] - pts[(i + 1) % n][0] * pts[i][1] for i in range(n))
    if area < 0:
        pts = pts[::-1]
    body_txt = ',\n    '.join(', '.join(f'{{{x:.4f}f, {y:.4f}f}}' for x, y in pts[i:i + 4])
                              for i in range(0, len(pts), 4))
    return f'constexpr ImVec2 kShape{name}[] = {{\n    {body_txt}}};\n'


